import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { makeServer } from './serve.mjs';
import { root } from './catalog.mjs';

const submissionOnly = process.argv.includes('--submission-only');
const out = path.join(root, submissionOnly ? 'artifacts/submission' : 'artifacts/performance'); await mkdir(out, { recursive: true });
const server = makeServer(path.join(root, 'dist')); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const report = { date: new Date().toISOString(), checks: [], samples: [], errors: [], screenshots: [], limitations: ['Local built site in Windows Chrome; no production deployment.', 'No Issue is submitted during verification. Resources stay in the author repository or Release.', 'Issue composer navigations use intercepted responses; GitHub login and actual submission are not tested.', ...(submissionOnly ? [] : ['The denied-fullscreen branch is explicitly simulated.', 'FPS measurements are specific to this machine and browser.', 'Visibility changes are explicitly simulated because headless Chrome keeps pages visible.'])] };
const check = (name, detail = true) => { report.checks.push({ name, detail }); console.log('PASS ' + name); };
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await context.newPage();
  const requests = [];
  const writeRequests = [];
  page.on('pageerror', error => report.errors.push(error.message));
  page.on('response', response => { if (response.status() >= 400) report.errors.push(`${response.status()} ${response.url()}`); });
  page.on('request', request => { requests.push(request.url()); if (!['GET', 'HEAD'].includes(request.method())) writeRequests.push(request.url()); });
  await page.goto(base); await page.locator('.game-card').last().waitFor();
  assert.equal(await page.locator('.game-card').count(), 3);
  assert.ok(!requests.some(url => /\/(game|render|three\.module)\.js/.test(url)));
  check('Hall loads covers and catalog without starting any games');
  await page.evaluate(() => { window.firstCard = document.querySelector('.game-card'); });
  await page.locator('#game-search').fill('轨道'); await page.waitForFunction(() => document.querySelectorAll('.game-card').length === 1);
  assert.equal(await page.evaluate(() => firstCard === document.querySelector('.game-card')), true);
  await page.locator('#game-search').fill(''); await page.waitForFunction(() => document.querySelectorAll('.game-card').length === 3);
  check('Search reuses game card nodes');
  await page.goto(base + '/#/submit'); await page.locator('#prepare-submission').waitFor({ state: 'visible' });
  await page.waitForFunction(() => !document.querySelector('#prepare-submission').disabled);
  const idea = new URL(await page.locator('#submit-idea').getAttribute('href'));
  assert.equal(idea.origin + idea.pathname, 'https://github.com/LanShiLiang/ai-game-lab/issues/new');
  assert.ok(idea.searchParams.get('title').startsWith('[设计想法]'));
  assert.match(idea.searchParams.get('body'), /没有游戏仓库也可以提交/);
  assert.equal(await page.locator('[name="repository"]').inputValue(), '');
  const receiverComposer = 'https://github.com/LanShiLiang/ai-game-lab/issues/new';
  assert.equal(await page.locator('#submission-receiver').getAttribute('href'), receiverComposer);
  assert.equal(await page.locator('#submission-receiver').innerText(), 'LanShiLiang/ai-game-lab');
  await context.route(url => url.origin + url.pathname === receiverComposer, route => route.fulfill({ status: 200, contentType: 'text/html', body: '<p>Issue composer navigation fixture</p>' }));
  const [ideaPage] = await Promise.all([page.waitForEvent('popup'), page.locator('#submit-idea').click()]);
  await ideaPage.waitForURL(idea.href);
  assert.equal(ideaPage.url(), idea.href);
  await ideaPage.close();
  await page.bringToFront();
  check('Design ideas directly open GitHub without filling the game form or supplying a repository');
  const openGameIssue = async () => {
    const [composer] = await Promise.all([page.waitForEvent('popup'), page.locator('#prepare-submission').click()]);
    await composer.waitForURL(url => url.origin + url.pathname === receiverComposer);
    const destination = new URL(composer.url());
    assert.equal(destination.href, await page.locator('#open-submission').getAttribute('href'));
    await composer.close(); await page.bringToFront();
    return destination;
  };
  const fields = { name: '轨道实验投稿', repository: 'https://github.com/creator/web-game', description: '沿轨道收集光点，避开障碍，抵达终点获胜。\n方向键移动，支持暂停和重开。', requirements: '无需后端', features: '' };
  const fieldNames = await page.locator('#submission-form').evaluate(form => [...form.elements].filter(field => field.name).map(field => field.name).sort());
  assert.deepEqual(fieldNames, Object.keys(fields).sort());
  for (const [key, value] of Object.entries(fields)) await page.locator(`#submission-form [name="${key}"]`).fill(value);
  const issue = await openGameIssue();
  assert.ok(await page.locator('#submission-form').evaluate(form => form.checkValidity()), 'Completed submission form is valid');
  await page.locator('#submission-preview').waitFor({ state: 'visible' });
  assert.equal(issue.origin + issue.pathname, 'https://github.com/LanShiLiang/ai-game-lab/issues/new');
  for (const key of ['description', 'requirements']) assert.ok(issue.searchParams.get('body').includes(fields[key]), `${key} preserved`);
  assert.doesNotMatch(issue.searchParams.get('body'), /构建方式|输出目录|## 创意特色/);
  assert.equal(await page.locator('input[type="file"]').count(), 0);
  assert.match(await page.locator('#submission-status').innerText(), /尚未提交/);
  check('Five-field game form directly opens the owner repository Issue composer with intact game details');
  await page.screenshot({ path: path.join(out, 'submission-desktop.png'), fullPage: true }); report.screenshots.push('submission-desktop.png');
  await page.locator('[name="repository"]').fill('https://github.com.evil.test/creator/game'); await page.locator('#prepare-submission').click();
  assert.equal(await page.locator('#submission-preview').isVisible(), false);
  assert.match(await page.locator('[name="repository"]').evaluate(node => node.validationMessage), /github/);
  check('Invalid repository blocks the draft without losing form data');
  await page.locator('[name="repository"]').fill(fields.repository);
  await page.locator('#submission-form [name="description"]').fill('   ');
  await page.locator('#prepare-submission').click();
  assert.equal(await page.locator('#submission-preview').isVisible(), false);
  assert.match(await page.locator('#submission-form [name="description"]').evaluate(node => node.validationMessage), /不能只输入空格/);
  await page.locator('#submission-form [name="description"]').fill(fields.description);
  check('Required game details reject whitespace without discarding the other sections');
  const longDescription = '每次收集光点都会切换轨道，在限时内抵达终点获胜。'.repeat(50);
  await page.locator('#submission-form [name="description"]').fill(longDescription);
  await page.locator('#prepare-submission').click();
  await page.locator('#submission-preview').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#submission-paste-hint').isVisible(), true);
  assert.equal(new URL(await page.locator('#open-submission').getAttribute('href')).searchParams.has('body'), false);
  assert.ok((await page.locator('#submission-draft').inputValue()).includes(longDescription));
  await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: base });
  await page.locator('#copy-submission').click();
  await page.waitForFunction(() => document.querySelector('#submission-status').textContent.includes('已复制'));
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  assert.equal(copied.replace(/\r\n/g, '\n'), await page.locator('#submission-draft').inputValue());
  assert.deepEqual(writeRequests, []);
  check('Long descriptions survive the copy flow; submission causes no server writes or uploads');
  await page.locator('#submission-form [name="description"]').fill(fields.description);
  const features = '每条轨道都会随节拍变换';
  await page.locator('[name="features"]').fill(features);
  await openGameIssue();
  await page.locator('#submission-preview').waitFor({ state: 'visible' });
  assert.ok(new URL(await page.locator('#open-submission').getAttribute('href')).searchParams.get('body').includes(features));
  check('Optional creative features are included when provided');
  await page.setViewportSize({ width: 360, height: 780 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(out, 'submission-mobile.png'), fullPage: true }); report.screenshots.push('submission-mobile.png');
  check('360px submission layout has no horizontal overflow');
  await page.setViewportSize({ width: 1280, height: 900 });
  if (!submissionOnly) {
  for (const id of ['orbit-dash', 'apex-rush', 'freight-fire']) {
    await page.goto(base + '/#/play/' + id); await page.locator('iframe.game-frame').waitFor();
    const frame = await (await page.locator('iframe.game-frame').elementHandle()).contentFrame();
    const start = id === 'orbit-dash' ? '#start-button' : '#start';
    if (id === 'freight-fire') await frame.locator('#loading').waitFor({ state: 'hidden', timeout: 180000 });
    if (id === 'apex-rush') await frame.waitForFunction(() => document.querySelector('#performance').textContent.includes('FPS'));
    await frame.locator(start).waitFor();
    await page.evaluate(() => { window.mountedFrame = document.querySelector('iframe'); });
    await page.locator('#expand-game').click();
    assert.ok(await page.evaluate(() => document.querySelector('#game-stage').getBoundingClientRect().height === innerHeight));
    assert.ok(await page.evaluate(() => mountedFrame === document.querySelector('iframe')));
    await page.locator('#exit-expanded').click();
    await page.locator('#fullscreen-game').click();
    await page.waitForFunction(() => document.fullscreenElement?.id === 'game-stage');
    assert.ok(await page.evaluate(() => mountedFrame === document.querySelector('iframe')));
    await page.locator('#exit-expanded').click(); await page.waitForFunction(() => !document.fullscreenElement);
    await frame.locator(start).click();
    if (id === 'apex-rush') await frame.locator('#hud').waitFor({ state: 'visible' });
    if (id === 'freight-fire') { await page.keyboard.press('Escape'); await frame.locator('#menu').waitFor({ state: 'visible' }); }
    await frame.locator(id === 'apex-rush' ? '#race-fullscreen' : id === 'freight-fire' ? '#menu-fullscreen' : '#fullscreen').click();
    await frame.waitForFunction(() => Boolean(document.fullscreenElement));
    await frame.evaluate(() => document.exitFullscreen());
    await page.waitForFunction(() => !document.fullscreenElement);
    const [popup] = await Promise.all([page.waitForEvent('popup'), page.locator('#standalone-game').click()]);
    await popup.waitForLoadState('domcontentloaded'); assert.ok(popup.url().includes(`/games/${id}/index.html`)); await popup.close();
    await page.bringToFront();
    check(`${id}: native full screen, expanded display, own full screen and independent window`);
    await page.screenshot({ path: path.join(out, `${id}-player.png`) }); report.screenshots.push(`${id}-player.png`);
  }
  await page.evaluate(() => { const stage = document.querySelector('#game-stage'); window.savedRequest = stage.requestFullscreen; stage.requestFullscreen = () => Promise.reject(new Error('QA denied')); });
  await page.locator('#fullscreen-game').click();
  assert.ok(await page.evaluate(() => document.body.classList.contains('game-expanded')));
  assert.match(await page.locator('#player-status').innerText(), /已铺满窗口/);
  await page.locator('#exit-expanded').click();
  await page.evaluate(() => { document.querySelector('#game-stage').requestFullscreen = savedRequest; });
  check('Denied full screen falls back to an expanded window with an exit button');
  await page.locator('.back-link').click(); await page.locator('iframe').waitFor({ state: 'detached' });
  assert.equal(await page.locator('iframe').count(), 0);
  assert.ok(await page.evaluate(() => !document.body.classList.contains('game-expanded')));
  check('Returning to the hall releases the previous iframe and display state');

  for (const [id, key] of [['apex-rush', '__apex'], ['freight-fire', '__freight']]) {
    const game = await browser.newPage({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 2 });
    game.on('pageerror', error => report.errors.push(error.message));
    const start = performance.now(); await game.goto(`${base}/games/${id}/?qa=1`);
    await game.waitForFunction(key => Boolean(window[key]?.view), key, { timeout: 180000 });
    const readyMs = performance.now() - start;
    await game.evaluate(key => { const renderer = window[key].view.renderer, render = renderer.render.bind(renderer); window.renders = 0; renderer.render = (...args) => { renders++; return render(...args); }; }, key);
    const sample = async phase => {
      await game.evaluate(() => { renders = 0; }); await game.waitForTimeout(2100);
      const state = await game.evaluate(key => ({ renders, pixelRatio: window[key].view.renderer.getPixelRatio(), stats: window[key].view.stats, paused: window[key].paused }), key);
      report.samples.push({ id, phase, readyMs, ...state }); return state;
    };
    const menu = await sample('menu'); assert.ok(menu.renders > 0 && menu.renders < 45);
    await game.locator('#start').click(); await game.waitForTimeout(1500);
    const play = await sample('playing'); assert.equal(play.paused, false); assert.ok(play.renders > menu.renders * 2);
    if (id === 'apex-rush') await game.locator('#pause-open').click(); else await game.evaluate(() => __freight.pause());
    const paused = await sample('paused'); assert.ok(paused.renders < play.renders / 2);
    check(`${id}: menu and pause reduce rendering while play retains its frame rate`, { menu: menu.renders, play: play.renders, paused: paused.renders });
    await game.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, get: () => true }); document.dispatchEvent(new Event('visibilitychange')); });
    const hidden = await sample('hidden-handler'); assert.equal(hidden.renders, 0);
    await game.evaluate(() => { delete document.hidden; document.dispatchEvent(new Event('visibilitychange')); });
    check(`${id}: hidden-page handler cancels all renderer calls`);
    await game.close();
  }
  }
  assert.deepEqual(report.errors, []);
  check('No page errors or failed HTTP assets');
} finally {
  await writeFile(path.join(out, 'after.json'), JSON.stringify(report, null, 2) + '\n');
  await browser.close(); await new Promise(resolve => server.close(resolve));
}
